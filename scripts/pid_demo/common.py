"""Shared helpers for the PID demo (pi0.5 on LIBERO): env/policy setup, observation batching,
candidate-object positions, camera projection.

Demo code for an explanation tab, not the main experiment pipeline.
"""

from __future__ import annotations

import os

os.environ.setdefault("MUJOCO_GL", "egl")

from typing import Any

import numpy as np
import torch

from lerobot.configs.policies import PreTrainedConfig
from lerobot.envs.configs import LiberoEnv as LiberoEnvConfig
from lerobot.envs.factory import make_env_pre_post_processors
from lerobot.envs.libero import LiberoEnv, _get_suite, get_libero_dummy_action
from lerobot.envs.utils import preprocess_observation
from lerobot.policies import make_policy, make_pre_post_processors

CKPT = "lerobot/pi05_libero_finetuned"
# google/paligemma-3b-pt-224 (the tokenizer named in the checkpoint) is gated on the Hub and no token is
# available here. We use the public big_vision PaliGemma sentencepiece model that OpenPI uses for pi0/pi0.5
# (gs://big_vision/paligemma_tokenizer.model), loaded with BOS on / EOS off like the HF tokenizer config.
TOKENIZER_DIR = os.environ.get("PID_DEMO_TOKENIZER_DIR", "/cache/pid_demo_dl/paligemma_tok_hf")
OBS_SIZE = 360  # LiberoEnv config default used by lerobot-eval
N_EXEC_DOCS = 10  # docs/source/libero.mdx: --policy.n_action_steps=10 (OpenPI setting)

# Fixture "handle sites": LIBERO's BDDL fixtures have no named handle sites, so we use the visual geom of the
# handle / knob (names are generated by the MJCF compiler and are stable for these scenes).
GOAL_FIXTURE_GEOMS = {
    "cabinet_top_drawer_handle": "wooden_cabinet_1_g17",
    "cabinet_middle_drawer_handle": "wooden_cabinet_1_g28",
    "stove_knob": "flat_stove_1_g4",
    "wine_rack": "wine_rack_1_g0",
}


def load_tokenizer():
    from transformers import GemmaTokenizer

    return GemmaTokenizer.from_pretrained(TOKENIZER_DIR, add_bos_token=True, add_eos_token=False)


def load_policy(device: str = "cuda") -> tuple[Any, Any, Any, Any, dict]:
    """Load pi0.5 exactly like lerobot-eval (policy.path=CKPT, n_action_steps=10)."""
    cfg = PreTrainedConfig.from_pretrained(CKPT)
    stored = {
        "chunk_size": cfg.chunk_size,
        "n_action_steps_stored": cfg.n_action_steps,
        "num_inference_steps": cfg.num_inference_steps,
        "dtype": getattr(cfg, "dtype", None),
        "normalization_mapping": {k: str(v) for k, v in cfg.normalization_mapping.items()},
        "compile_model_stored": getattr(cfg, "compile_model", None),
    }
    cfg.pretrained_path = CKPT
    cfg.device = device
    cfg.n_action_steps = N_EXEC_DOCS
    cfg.compile_model = False  # avoid torch.compile max-autotune warmup for a short demo
    env_cfg = LiberoEnvConfig(task="libero_goal")
    policy = make_policy(cfg=cfg, env_cfg=env_cfg)
    policy.eval()
    pre, post = make_pre_post_processors(
        policy_cfg=cfg,
        pretrained_path=CKPT,
        preprocessor_overrides={
            "device_processor": {"device": device},
            "rename_observations_processor": {"rename_map": {}},
            "tokenizer_processor": {"tokenizer": load_tokenizer()},
        },
    )
    env_pre, _ = make_env_pre_post_processors(env_cfg=env_cfg, policy_cfg=cfg)
    stored["n_action_steps_used"] = cfg.n_action_steps
    return policy, pre, post, env_pre, stored


def make_env(suite_name: str, task_id: int, init_state_id: int = 0) -> LiberoEnv:
    suite = _get_suite(suite_name)
    return LiberoEnv(
        suite,
        task_id,
        suite_name,
        obs_type="pixels_agent_pos",
        observation_height=OBS_SIZE,
        observation_width=OBS_SIZE,
        episode_index=init_state_id,
    )


def _batchify(x):
    if isinstance(x, dict):
        return {k: _batchify(v) for k, v in x.items()}
    return np.asarray(x)[None]


def obs_to_batch(obs: dict, task: str, env_pre, pre, repeat: int = 1) -> dict:
    """Single LiberoEnv observation -> policy input batch (same path as lerobot_eval.rollout)."""
    batch = preprocess_observation(_batchify(obs))
    batch["task"] = [task]
    batch = env_pre(batch)
    batch = pre(batch)
    if repeat > 1:
        batch = {
            k: (v.repeat(repeat, *([1] * (v.ndim - 1))) if isinstance(v, torch.Tensor) else v)
            for k, v in batch.items()
        }
    return batch


@torch.no_grad()
def sample_chunks(policy, post, batch: dict, seed: int) -> np.ndarray:
    """K chunks with independent flow-matching noise (one GPU batch). Returns unnormalized (K, chunk, 7)."""
    torch.manual_seed(seed)
    actions = policy.predict_action_chunk(batch)
    actions = post(actions)
    return actions.float().cpu().numpy()


def dummy_steps(env: LiberoEnv, n: int) -> dict:
    raw = None
    for _ in range(n):
        raw, _, _, _ = env._env.step(get_libero_dummy_action())
    return env._format_raw_obs(raw)


def sim_handles(env: LiberoEnv):
    e = env._env.env
    return e, e.sim.model, e.sim.data


def base_frame(env: LiberoEnv) -> tuple[np.ndarray, np.ndarray]:
    _, m, d = sim_handles(env)
    bid = m.body_name2id("robot0_base")
    return d.body_xpos[bid].copy(), d.body_xmat[bid].reshape(3, 3).copy()


def to_base(env: LiberoEnv, pts_world: np.ndarray) -> np.ndarray:
    pos, rot = base_frame(env)
    return (np.asarray(pts_world) - pos) @ rot


def eef_world(env: LiberoEnv) -> np.ndarray:
    _, m, d = sim_handles(env)
    return d.site_xpos[m.site_name2id("gripper0_grip_site")].copy()


def candidate_positions_world(env: LiberoEnv) -> dict[str, np.ndarray]:
    """BDDL objects (body origin) + fixture handle/knob geoms (Goal) in world frame."""
    e, m, d = sim_handles(env)
    out: dict[str, np.ndarray] = {}
    for name in e.objects_dict:
        out[name.removesuffix("_1")] = d.body_xpos[e.obj_body_id[name]].copy()
    for label, geom in GOAL_FIXTURE_GEOMS.items():
        if any(fx in geom for fx in e.fixtures_dict):
            out[label] = d.geom_xpos[m.geom_name2id(geom)].copy()
    return out


def sim_state(env: LiberoEnv) -> np.ndarray:
    return env._env.env.sim.get_state().flatten().copy()


def camera_matrix(env: LiberoEnv, cam: str = "agentview") -> np.ndarray:
    from robosuite.utils.camera_utils import get_camera_transform_matrix

    return get_camera_transform_matrix(env._env.env.sim, cam, OBS_SIZE, OBS_SIZE)


def project_display(world_to_pix: np.ndarray, pts_world: np.ndarray) -> np.ndarray:
    """World points -> (x, y) pixel coords on the display image (raw image rotated 180 deg, as the policy sees it).

    robosuite returns (row, col) for the vertically flipped render; the display image additionally flips
    columns.
    """
    pts = np.atleast_2d(pts_world)
    h = np.concatenate([pts, np.ones((len(pts), 1))], axis=1) @ world_to_pix.T
    col = h[:, 0] / h[:, 2]
    row = h[:, 1] / h[:, 2]
    return np.stack([OBS_SIZE - 1 - col, row], axis=1)


def display_img(img: np.ndarray) -> np.ndarray:
    return np.ascontiguousarray(img[::-1, ::-1])
