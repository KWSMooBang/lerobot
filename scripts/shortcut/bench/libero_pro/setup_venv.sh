#!/usr/bin/env bash
# LIBERO-PRO client environment for sc-bench (T013). No sudo / apt; idempotent (re-run = check + fill gaps).
#
#   scripts/shortcut/bench/libero_pro/setup_venv.sh [--jobs 16] [--skip-env-axis]
#
# <repo>/.venvs/libero_pro_src  Zxy-MLlab/LIBERO-PRO at $LIBERO_PRO_SHA (code MIT; its own `libero` package +
#                               assets incl. PRO's extra objects) + the HF dataset's bddl/init files copied in
# <repo>/.venvs/libero_pro_hf   zhouxueyang/LIBERO-Pro (CC-BY-4.0) at $LIBERO_PRO_HF_REV
# <repo>/.venvs/libero_pro      uv venv, Python 3.12, robosuite 1.4.0 + mujoco 3.8.1 (= the main venv's
#                               hf-libero stack), PRO's libero editable, numpy / msgpack / websockets (client)
#                               + libero_config/config.yaml (LIBERO_CONFIG_PATH; ~/.libero is never touched)
# Environment axis: generated by gen_env_axis.py (not in the HF dataset). SC_VERSION = bench_version.
set -euo pipefail

LIBERO_PRO_SHA=${LIBERO_PRO_SHA:-eafdb809426b13153aa1e4c42d6601844217dfec}
LIBERO_PRO_HF_REV=${LIBERO_PRO_HF_REV:-c86fc3b8293185a6f373677018ff3e37f8391602}
JOBS=16; ENV_AXIS=1
while [ $# -gt 0 ]; do
  case "$1" in
    --jobs) JOBS=$2; shift ;;
    --skip-env-axis) ENV_AXIS=0 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
  shift
done

HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../../../.." && pwd)
D=$REPO/.venvs
SRC=$D/libero_pro_src
HF=$D/libero_pro_hf
VENV=$D/libero_pro
LIB=$SRC/libero/libero
mkdir -p "$D"
note() { echo "[libero_pro setup] $*"; }

# ------------------------------------------------------------ source
if [ ! -d "$SRC/.git" ]; then
  note "clone LIBERO-PRO"
  git clone --quiet https://github.com/Zxy-MLlab/LIBERO-PRO "$SRC"
fi
if [ "$(git -C "$SRC" rev-parse HEAD)" != "$LIBERO_PRO_SHA" ]; then
  git -C "$SRC" fetch --quiet origin "$LIBERO_PRO_SHA" || git -C "$SRC" fetch --quiet --unshallow || true
  git -C "$SRC" checkout --quiet "$LIBERO_PRO_SHA"
fi

# ------------------------------------------------------------ venv
if [ ! -x "$VENV/bin/python" ]; then
  uv venv --quiet "$VENV" --python 3.12
fi
note "install packages into $VENV"
uv pip install --quiet --python "$VENV/bin/python" \
  robosuite==1.4.0 mujoco==3.8.1 bddl==1.0.1 numpy==2.2.6 gym==0.26.2 pyyaml easydict termcolor future \
  cloudpickle matplotlib opencv-python-headless imageio imageio-ffmpeg msgpack websockets pytest
# `libero/` has no __init__.py (namespace package), so a PEP 660 editable install maps nothing; put the
# source dir on sys.path like the legacy `setup.py develop` the LIBERO README relies on.
uv pip uninstall --quiet --python "$VENV/bin/python" libero 2>/dev/null || true
SITE=$("$VENV/bin/python" -c 'import sysconfig; print(sysconfig.get_paths()["purelib"])')
echo "$SRC" >"$SITE/libero_pro_src.pth"

# ------------------------------------------------------------ PRO dataset (bddl + init files of 4 axes)
if [ ! -f "$HF/.rev" ] || [ "$(cat "$HF/.rev")" != "$LIBERO_PRO_HF_REV" ]; then
  note "download zhouxueyang/LIBERO-Pro@$LIBERO_PRO_HF_REV"
  HF_HUB_DISABLE_PROGRESS_BARS=1 uv run --quiet --no-project --with huggingface_hub \
    hf download zhouxueyang/LIBERO-Pro --repo-type dataset --revision "$LIBERO_PRO_HF_REV" --local-dir "$HF" >/dev/null
  echo "$LIBERO_PRO_HF_REV" >"$HF/.rev"
fi
for kind in bddl_files init_files; do
  for d in "$HF/$kind"/libero_*; do
    mkdir -p "$LIB/$kind/$(basename "$d")"
    cp -n "$d"/* "$LIB/$kind/$(basename "$d")/"
  done
done

# ------------------------------------------------------------ LIBERO config (PRO's own assets / files)
mkdir -p "$VENV/libero_config"
cat >"$VENV/libero_config/config.yaml" <<EOF
assets: $LIB/assets
bddl_files: $LIB/bddl_files
benchmark_root: $LIB
datasets: $LIB/../datasets
init_states: $LIB/init_files
EOF

# ------------------------------------------------------------ environment axis
if [ "$ENV_AXIS" = 1 ]; then
  note "generate environment axis (bddl + 50 inits per task, CPU, $JOBS processes)"
  CUDA_VISIBLE_DEVICES="" "$VENV/bin/python" "$HERE/gen_env_axis.py" --jobs "$JOBS" | tail -n 3
fi

# ------------------------------------------------------------ version stamp, check, sizes
ENV_HASH=$(cat "$LIB"/bddl_files/libero_*_env/*.bddl "$LIB"/init_files/libero_*_env/*.pruned_init 2>/dev/null | sha256sum | cut -c1-8)
echo "libero-pro-${LIBERO_PRO_SHA:0:8}/hf-${LIBERO_PRO_HF_REV:0:8}/env-${ENV_HASH}" >"$SRC/SC_VERSION"
note "bench_version $(cat "$SRC/SC_VERSION")"
"$VENV/bin/python" "$HERE/check_install.py"
note "sizes: $(du -sh "$VENV" | cut -f1) venv, $(du -sh "$SRC" | cut -f1) source+assets+files, $(du -sh "$HF" | cut -f1) dataset"
